import base64, json, re, subprocess
tpl = open('part_css.html').read() + open('part_body.html').read() + open('part_js.html').read()
open('template.html', 'w').write(tpl)
f1 = base64.b64encode(open('fonts/bedstead-sub.woff2', 'rb').read()).decode()
f2 = base64.b64encode(open('fonts/lakicaps-sub.woff2', 'rb').read()).decode()
data = json.load(open('data.json'))
js = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/').replace('<!--', '<\\u0021--')
out = tpl.replace('__FONT_B64__', f1).replace('__FONT2_B64__', f2).replace('__DATA__', js)
open('laki-tv.html', 'w').write(out)
scripts = re.findall(r'<script>(.*?)</script>', out, flags=re.S)
open('/tmp/lakitv_check.js', 'w').write(scripts[-1])
r = subprocess.run(['node', '-e', 'new Function(require("fs").readFileSync("/tmp/lakitv_check.js","utf8"))'], capture_output=True, text=True)
print('syntax', 'OK' if r.returncode == 0 else r.stderr[:800])
print(len(out), 'bytes')
# Esikatselukääre (julkaisussa isäntä lisää vastaavan dokumenttirungon)
open('preview.html', 'w').write('<!doctype html><html lang="fi"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body>' + out + '</body></html>')
